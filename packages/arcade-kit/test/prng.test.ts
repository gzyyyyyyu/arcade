describe('prng：和各游戏原来的实现逐位相同', () => {
  it('hashSeed（牌馆、开盘）', () => {
    for (const [parts, v] of HASH_SEED) expect(hashSeed(...parts)).toBe(v);
  });

  it('createRng：u32、next、int、shuffle、pick 接着同一条流', () => {
    for (const v of CREATE_RNG) {
      const r = createRng(v.seed);
      // 原实现只有 next()：u32 = next × 2³²，两者等价
      expect(Array.from({ length: 8 }, () => Math.round(r.next() * 4294967296))).toEqual(v.u32);
      expect(INTS.map((n) => r.int(n))).toEqual(v.int);
      expect(r.shuffle(Array.from({ length: 12 }, (_, i) => i))).toEqual(v.shuffle);
      expect(r.pick(['a', 'b', 'c', 'd', 'e'])).toBe(v.pick);
    }
  });

  it('rngFor = createRng(hashSeed(...))', () => {
    for (const [parts, seq] of RNG_FOR) {
      const r = rngFor(...parts);
      expect(Array.from({ length: 8 }, () => r.u32())).toEqual(seq);
    }
  });

  it('hash32（海岛、夜巡）', () => {
    for (const [text, seed, v] of HASH32) expect(hash32(text, seed)).toBe(v);
  });

  it('streamRng：初始状态、u32、两种 int 取法、走完后的状态', () => {
    for (const v of STREAM) {
      const h = streamRng(v.seed, v.stream);
      expect(h.snapshot()).toEqual(v.snapshot);
      expect(Array.from({ length: 8 }, () => h.u32())).toEqual(v.u32);
      expect(INTS.map((n) => intModulo(h, n))).toEqual(v.intModulo);
      expect(h.snapshot()).toEqual(v.snapshotAfter);
      const y = streamRng(v.seed, v.stream);
      for (let i = 0; i < 8; i++) y.u32();
      expect(INTS.map((n) => y.int(n))).toEqual(v.intFloor);
    }
  });

  it('Sfc32 的空转次数可调，默认 12', () => {
    const a = new Sfc32(1, 2, 3, 4);
    const b = new Sfc32(1, 2, 3, 4, 0);
    for (let i = 0; i < 12; i++) b.u32();
    expect(a.snapshot()).toEqual(b.snapshot());
  });

  it('pick 空列表报错', () => {
    expect(() => createRng(1).pick([])).toThrow();
  });
});
