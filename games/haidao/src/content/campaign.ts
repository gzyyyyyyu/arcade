type Row = [BuildingKind, number, number, number];

/** 按行 [种类, 等级, x, y] 排布，id 从 1 起 */
function layout(rows: Row[]): Placed[] {
  return rows.map(([kind, level, x, y], i) => {
    const p: Placed = { id: i + 1, kind, level, x, y };
    return p;
  });
}

/** 装饰：每关点缀几棵树，位置都在空地上 */
const PALMS = (pts: Array<[number, number]>): Row[] => pts.map(([x, y]) => ['palm', 1, x, y]);

